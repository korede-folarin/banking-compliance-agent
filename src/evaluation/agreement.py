"""
Run-to-run agreement (P8-10), zero API cost: reads a saved main pass.

For each (document, outcome), do the repeated runs give the same judge verdict
(`llm_status`, before the confidence override)? And where do the wrong verdicts
sit: among pairs whose runs agree, or among pairs whose runs disagree? If
errors concentrate where runs disagree, disagreement is a review signal that
costs nothing beyond running more than once.

Scoring matches `run_eval summary`: potentially_non_compliant counts as
non_compliant, and insufficient_evidence is an abstention, counted
separately, never as right or wrong.

    python -m src.evaluation.agreement [--input docs/eval_raw_main_pass_v2.jsonl] [--output <md>]

The report defaults to docs/eval_agreement_<input stem>.md, next to the input.
"""

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from src.evaluation.run_eval import INPUT_HELP, resolve_main_input  # noqa: E402
from tests.fixtures.eval_set import OUTCOME_KEYS  # noqa: E402

ABSTAIN = "insufficient_evidence"


def _verdict(status: str) -> str:
    return "non_compliant" if status == "potentially_non_compliant" else status


def pair_table(rows: list[dict], status_field: str = "llm_status") -> list[dict]:
    """One entry per (doc, outcome): the verdict per run, the label, agreement, and wrong/abstained counts."""
    pairs: dict[tuple, dict] = {}
    for r in rows:
        for k in OUTCOME_KEYS:
            p = pairs.setdefault((r["doc_id"], k), {"doc_id": r["doc_id"], "outcome": k,
                                                    "label": r["ground_truth"][k], "runs": {}})
            p["runs"][r["run_idx"]] = r["outcomes"][k][status_field]
    out = []
    for p in sorted(pairs.values(), key=lambda p: (p["doc_id"], OUTCOME_KEYS.index(p["outcome"]))):
        verdicts = [p["runs"][i] for i in sorted(p["runs"])]
        p["verdicts"] = verdicts
        p["agree"] = len(set(verdicts)) == 1
        p["wrong"] = sum(v != ABSTAIN and _verdict(v) != p["label"] for v in verdicts)
        p["abstained"] = verdicts.count(ABSTAIN)
        counts = {v: verdicts.count(v) for v in set(verdicts)}
        top = max(counts.values())
        majority = [v for v, c in counts.items() if c == top]
        p["majority"] = majority[0] if len(majority) == 1 else None  # None: no single majority
        p["majority_correct"] = (p["majority"] is not None and p["majority"] != ABSTAIN
                                 and _verdict(p["majority"]) == p["label"])
        out.append(p)
    return out


def summarise(pairs: list[dict]) -> dict:
    def block(ps):
        return {"pairs": len(ps), "verdicts": sum(len(p["verdicts"]) for p in ps),
                "wrong": sum(p["wrong"] for p in ps), "abstained": sum(p["abstained"] for p in ps)}
    agree = [p for p in pairs if p["agree"]]
    disagree = [p for p in pairs if not p["agree"]]
    runs = sorted({len(p["verdicts"]) for p in pairs})
    s = {"runs_per_pair": runs, "all": block(pairs), "agree": block(agree), "disagree": block(disagree),
         "by_outcome": {k: {"agree": sum(p["agree"] for p in pairs if p["outcome"] == k),
                            "pairs": sum(p["outcome"] == k for p in pairs)} for k in OUTCOME_KEYS},
         "disagree_majority_correct": sum(p["majority_correct"] for p in disagree)}
    # With 0 errors in n agreeing pairs, the "rule of three" gives an approximate 95% upper bound of 3/n
    # on the per-pair rate of all runs agreeing on a wrong verdict.
    n = len(agree)
    s["agree_wrong_pairs"] = sum(p["wrong"] > 0 for p in agree)
    s["agree_wrong_upper_95"] = round(3 / n, 4) if n and s["agree_wrong_pairs"] == 0 else None
    return s


def write_report(pairs: list[dict], s: dict, input_path: Path, output_path: Path) -> None:
    a, d = s["agree"], s["disagree"]
    L = ["# Run-to-run agreement (P8-10)", "",
         f"Input: `{input_path.name}`. Judge verdicts (`llm_status`, before the confidence override). "
         f"Runs per (document, outcome): {s['runs_per_pair']}. Generated by `src/evaluation/agreement.py` "
         "(zero API cost).", "",
         "Scoring as in `run_eval summary`: potentially_non_compliant counts as non_compliant; "
         "insufficient_evidence is an abstention, not counted as right or wrong.", "",
         "## Result", "",
         "| | Pairs | Verdicts | Wrong | Abstained |", "|---|---|---|---|---|",
         f"| Runs agree | {a['pairs']} | {a['verdicts']} | {a['wrong']} | {a['abstained']} |",
         f"| Runs disagree | {d['pairs']} | {d['verdicts']} | {d['wrong']} | {d['abstained']} |",
         f"| All | {s['all']['pairs']} | {s['all']['verdicts']} | {s['all']['wrong']} | {s['all']['abstained']} |", ""]
    if a["wrong"] == 0 and s["all"]["wrong"]:
        L.append(f"Every wrong verdict ({s['all']['wrong']}) is in a pair whose runs disagree; "
                 f"no pair has all runs agreeing on a wrong verdict.")
    else:
        L.append(f"{a['wrong']} of {s['all']['wrong']} wrong verdicts are in pairs whose runs agree.")
    if s["agree_wrong_upper_95"] is not None:
        L.append(f"With 0 such pairs in {a['pairs']}, the approximate 95% upper bound on the rate of pairs where "
                 f"every run agrees on a wrong verdict is {s['agree_wrong_upper_95']:.1%} (rule of three). "
                 "This set has 15 synthetic documents; it is not evidence about other documents.")
    L.append(f"Majority vote in the disagreeing pairs: correct in {s['disagree_majority_correct']} of {d['pairs']}.")
    L += ["", "## By outcome", "", "| Outcome | Pairs where runs agree |", "|---|---|"]
    for k, b in s["by_outcome"].items():
        L.append(f"| {k} | {b['agree']} of {b['pairs']} |")
    L += ["", "## Pairs whose runs disagree", "", "| Document | Outcome | Label | Verdicts by run | Wrong | Majority |",
          "|---|---|---|---|---|---|"]
    for p in pairs:
        if not p["agree"]:
            L.append(f"| {p['doc_id']} | {p['outcome']} | {p['label']} | {', '.join(p['verdicts'])} | {p['wrong']} | "
                     f"{p['majority'] or 'none'} ({'correct' if p['majority_correct'] else 'not correct'}) |")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(L) + "\n", encoding="utf-8")


def _read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description="Run-to-run agreement (zero API cost)")
    parser.add_argument("--input", help=INPUT_HELP)
    parser.add_argument("--output", help="Report path (default docs/eval_agreement_<input stem>.md)")
    args = parser.parse_args(argv)
    input_path = resolve_main_input(args.input)
    output_path = Path(args.output) if args.output else input_path.with_name(f"eval_agreement_{input_path.stem}.md")
    if output_path.resolve() == input_path.resolve():
        raise SystemExit("Refusing to overwrite the input.")
    pairs = pair_table(_read_jsonl(input_path))
    s = summarise(pairs)
    write_report(pairs, s, input_path, output_path)
    print(json.dumps({k: v for k, v in s.items() if k != "by_outcome"}, indent=2))
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
